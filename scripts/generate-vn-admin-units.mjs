// Regenerates app/entities/address/vn-admin-units.constants.ts from a downloaded copy of
// https://provinces.open-api.vn/api/v2/?depth=2 (Vietnam's two-level administrative units, in force 01/07/2025).
//
//   curl -o <download-dir>/units.json "https://provinces.open-api.vn/api/v2/?depth=2"
//   node scripts/generate-vn-admin-units.mjs <download-dir>/units.json
//   pnpm exec prettier --write app/entities/address/vn-admin-units.constants.ts
//
// The file is only read as JSON; only names and province codes are kept.
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const OUTPUT = fileURLToPath(new URL('../app/entities/address/vn-admin-units.constants.ts', import.meta.url))

const source = process.argv[2]
if (!source) {
  console.error('Usage: node scripts/generate-vn-admin-units.mjs <units.json>')
  process.exit(1)
}

const provinces = JSON.parse(await readFile(source, 'utf8'))
if (!Array.isArray(provinces) || provinces.some((province) => !Array.isArray(province.wards))) {
  throw new Error('Expected the provinces array of API v2 with depth=2 (each province with its wards).')
}

const text = (value) => {
  if (typeof value !== 'string' || !value.trim() || /['\\\n]/.test(value)) throw new Error(`Unexpected name: ${value}`)
  return `'${value.trim()}'`
}
const wardCount = provinces.reduce((sum, province) => sum + province.wards.length, 0)
const body = provinces
  .map(
    (province) =>
      `  { code: ${Number(province.code)}, name: ${text(province.name)}, wards: [${province.wards
        .map((ward) => text(ward.name))
        .join(', ')}] }`
  )
  .join(',\n')

await writeFile(
  OUTPUT,
  `/**
 * Vietnam's administrative units after the 2025 reorganisation, in force from 01/07/2025: ${provinces.length} provinces and
 * centrally run cities, each with its wards, communes and special zones (${wardCount} in all). There is no district level.
 * Generated by \`scripts/generate-vn-admin-units.mjs\` from provinces.open-api.vn (API v2); do not edit by hand.
 */
export interface AdminProvince {
  code: number
  name: string
  wards: readonly string[]
}

export const VN_PROVINCES: readonly AdminProvince[] = [
${body}
]
`
)
console.log(`Wrote ${provinces.length} provinces and ${wardCount} wards to ${OUTPUT}`)
